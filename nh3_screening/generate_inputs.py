def main():
    base_dir = "nh3_screening"
    
    for dopant in DOPANTS:
        if dopant == 'Ni':
            dir_name = f"{base_dir}/pure_Ni"
        else:
            dir_name = f"{base_dir}/Ni_{dopant}"
        
        os.makedirs(dir_name, exist_ok=True)
        
        # --- 裸 slab (bare) ---
        bare_dir = f"{dir_name}/01_bare"
        os.makedirs(bare_dir, exist_ok=True)
        
        poscar = generate_ni111_poscar(27, dopant)
        with open(f"{bare_dir}/POSCAR", 'w') as f:
            f.write(poscar)
        
        with open(f"{bare_dir}/INCAR", 'w') as f:
            f.write(INCAR_TEMPLATE.format(
                dopant=dopant,
                job_type="bare",
                system_name=f"Ni111_{dopant}_bare"
            ))
        
        with open(f"{bare_dir}/KPOINTS", 'w') as f:
            f.write(KPOINTS_CONTENT)
        
        # POTCAR 占位符
        elements = sorted(set(['Ni', dopant])) if dopant != 'Ni' else ['Ni']
        with open(f"{bare_dir}/POTCAR", 'w') as f:
            f.write(f"# POTCAR for {' '.join(elements)}\n")
            f.write("# Run: cat $POTCAR_LIB/POTCAR_{element1} $POTCAR_LIB/POTCAR_{element2} > POTCAR\n")
        
        # --- N 吸附 (N_ads) ---
        ads_dir = f"{dir_name}/02_N_ads"
        os.makedirs(ads_dir, exist_ok=True)
        
        # 复制 POSCAR 并加上 N 原子（手动放置 N 到 fcc hollow 位）
        with open(f"{ads_dir}/POSCAR", 'w') as f:
            f.write(poscar)  # 需要手动添加 N 原子并微调位置
        
        with open(f"{ads_dir}/INCAR", 'w') as f:
            f.write(INCAR_ADS.format(
                dopant=dopant,
                job_type="N_ads",
                system_name=f"Ni111_{dopant}_N_ads"
            ))
        
        with open(f"{ads_dir}/KPOINTS", 'w') as f:
            f.write(KPOINTS_CONTENT)
        
        # --- 提交脚本 (Slurm) ---
        sub_dir = dir_name
        with open(f"{sub_dir}/run_vasp.sh", 'w') as f:
            f.write(f"""#!/bin/bash
#SBATCH -J NH3_{dopant}
#SBATCH -N 1
#SBATCH -n 32
#SBATCH -t 48:00:00

module load vasp/6.4

# Step 1: Bare slab relaxation
cd 01_bare
mpirun vasp_std
cd ..

# Step 2: N adsorption
cd 02_N_ads
mpirun vasp_std
cd ..

echo "Done: {dopant} on Ni(111)"
""")
        
        print(f"✅ Generated: {dir_name}")

