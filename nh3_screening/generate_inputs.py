def generate_ni111_poscar(ni_sites, dopant, replace_idx=0):
    """
    生成 Ni(111) p(3x3) slab 的 POSCAR.
    3 层，每层 9 个 Ni 原子。
    第 replace_idx 个表面原子替换为 dopant.
    """
    # Ni(111) 原子坐标（分数坐标）
    # Layer 1 (bottom), Layer 2, Layer 3 (surface)
    layer1 = [
        (0.00000, 0.00000, 0.08000),
        (0.33333, 0.16667, 0.08000),
        (0.66667, 0.33333, 0.08000),
        (0.00000, 0.33333, 0.08000),
        (0.33333, 0.50000, 0.08000),
        (0.66667, 0.66667, 0.08000),
        (0.00000, 0.66667, 0.08000),
        (0.33333, 0.83333, 0.08000),
        (0.66667, 0.00000, 0.08000),
    ]
    layer2 = [
        (0.11111, 0.22222, 0.14667),
        (0.44444, 0.38889, 0.14667),
        (0.77778, 0.55556, 0.14667),
        (0.11111, 0.55556, 0.14667),
        (0.44444, 0.72222, 0.14667),
        (0.77778, 0.88889, 0.14667),
        (0.11111, 0.88889, 0.14667),
        (0.44444, 0.05556, 0.14667),
        (0.77778, 0.22222, 0.14667),
    ]
    layer3 = [
        (0.00000, 0.00000, 0.21333),
        (0.33333, 0.16667, 0.21333),
        (0.66667, 0.33333, 0.21333),
        (0.00000, 0.33333, 0.21333),
        (0.33333, 0.50000, 0.21333),
        (0.66667, 0.66667, 0.21333),
        (0.00000, 0.66667, 0.21333),
        (0.33333, 0.83333, 0.21333),
        (0.66667, 0.00000, 0.21333),
    ]
    
    all_atoms = []
    for (x, y, z) in layer1:
        all_atoms.append(('Ni', x, y, z))
    for (x, y, z) in layer2:
        all_atoms.append(('Ni', x, y, z))
    
    # 第三层（表面层），第 replace_idx 个替换为掺杂原子
    for i, (x, y, z) in enumerate(layer3):
        if i == replace_idx and dopant != 'Ni':
            all_atoms.append((dopant, x, y, z))
        else:
            all_atoms.append(('Ni', x, y, z))
    
    # 统计原子数
    n_ni = sum(1 for a in all_atoms if a[0] == 'Ni')
    n_dop = sum(1 for a in all_atoms if a[0] != 'Ni')
    
    # 格式化为 POSCAR
    lines = []
    lines.append(f"Ni(111) p(3x3) - {dopant} doped")
    lines.append("   1.00000000000000")
    lines.append(f"     {1.5*A:.6f}    {-2.5980762114*A*0.57735:.6f}    0.0000000000")
    lines.append(f"     {1.5*A:.6f}    {2.5980762114*A*0.57735:.6f}    0.0000000000")
    lines.append(f"     0.0000000000    0.0000000000    {C:.6f}")
    
    if n_dop > 0:
        lines.append(f"  {n_ni}  {n_dop}")
    else:
        lines.append(f"  {n_ni}")
    
    lines.append("Selective Dynamics")
    lines.append("Direct")
    
    for i, (elem, x, y, z) in enumerate(all_atoms):
        # 底层两层固定，表面层（第三层）可动
        if i < 18:  # layer 1 + layer 2
            lines.append(f"  {x:.8f}  {y:.8f}  {z:.8f}  F  F  F")
        else:
            lines.append(f"  {x:.8f}  {y:.8f}  {z:.8f}  T  T  T")
    
    return '\n'.join(lines)


def write_potcar(elements):
    """
    生成 POTCAR 文件（需要事先准备好 POTCAR 库）
    实际使用需要连接 POTCAR 库路径
    """
    lines = []
    for elem in elements:
        lines.append(f"# POTCAR for {elem}")
    return '\n'.join(lines) + '\n# NOTE: 需要从 POTCAR 库中 cat 对应的 POTCAR 文件'


